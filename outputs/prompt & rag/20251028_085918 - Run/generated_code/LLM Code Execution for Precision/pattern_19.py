def execute_generated_code(code_string):
    """
    Executes the generated Python code securely and captures its output.
    """
    st.info("Executing generated financial code...")
    local_vars = {}
    try:
        # Redirect stdout to capture print statements, if any
        # In this specific case, the generated code assigns to _computation_results
        # so stdout redirection is less critical but good practice for general exec()
        with contextlib.redirect_stdout(io.StringIO()) as f:
            exec(code_string, {}, local_vars)
        # The generated code assigns results to a specific variable name `_computation_results`
        if '_computation_results' in local_vars:
            return local_vars['_computation_results']
        else:
            st.error("Generated code did not produce expected '_computation_results'.")
            return None
    except Exception as e:
        st.error(f"Error executing code: {e}")
        return None

def simulate_llm_synthesis(financial_results, financial_goals, current_investments, risk_tolerance):
    """
    Simulates an LLM synthesizing the numerical results into a natural language strategy.
    In a real application, this would be another LLM call with the results and user inputs.
    """
    st.info("LLM is synthesizing the investment strategy...")
    if not financial_results:
        return "Could not generate an investment strategy due to computation errors."

    strategy_output = []
    strategy_output.append("### Personalized Investment Strategy and Risk Assessment\n")
    strategy_output.append(f"Based on your financial goals: '{financial_goals}', current investment of ${current_investments:,.2f}, and a risk tolerance of {risk_tolerance}/10, here's a detailed strategy.\n")

    # Portfolio Optimization Results
    strategy_output.append("#### 1. Optimal Asset Allocation (Minimum Volatility Portfolio)\n")
    min_vol_portfolio = financial_results['min_vol_portfolio']
    asset_names = financial_results['asset_names']
    strategy_output.append("To achieve a portfolio with minimized volatility for a given level of return, consider the following allocation:\n")
    for i, weight in enumerate(min_vol_portfolio['weights']):
        strategy_output.append(f"- **{asset_names[i]}**: {weight:.2%}\n")
    strategy_output.append(f"This optimized portfolio is expected to have an annual return of {min_vol_portfolio['return']:.2%} with an annual volatility of {min_vol_portfolio['volatility']:.2%}.\n")

    # Monte Carlo Simulation Results
    strategy_output.append("#### 2. Future Growth Projections and Risk Assessment (Monte Carlo Simulation)\n")
    monte_carlo_results = financial_results['monte_carlo']
    strategy_output.append(f"Over the next 10 years, with your current investment and risk profile, our simulations project the following outcomes:\n")
    strategy_output.append(f"- **Median Projected Value**: ${monte_carlo_results['median_final_value']:.2f}\n")
    strategy_output.append(f"- There is a 5% chance your investment could fall below **${monte_carlo_results['percentile_5th']:.2f}**.\n")
    strategy_output.append(f"- There is a 5% chance your investment could exceed **${monte_carlo_results['percentile_95th']:.2f}**.\n")
    strategy_output.append(f"- The probability of experiencing a loss (ending below your initial investment) is approximately **{monte_carlo_results['loss_probability']:.2%}**. \n")
    strategy_output.append("This indicates the potential range of outcomes, helping you understand the inherent risks and rewards.\n")

    strategy_output.append("#### 3. Recommendations\n")
    # Example recommendation logic based on risk tolerance and simulation results
    if risk_tolerance >= 7:
        strategy_output.append("Given your high risk tolerance, the strategy leans towards growth-oriented assets. You might consider exploring additional higher-growth opportunities, but always ensure diversification.\n")
    elif risk_tolerance >= 4:
        strategy_output.append("Your moderate risk tolerance suggests a balanced approach. The recommended portfolio aims for a good balance between growth and stability. Regular rebalancing is advised.\n")
    else:
        strategy_output.append("With a lower risk tolerance, capital preservation is key. The portfolio emphasizes stability. Consider fixed-income assets and regular review of your financial plan.\n")

    strategy_output.append("\n*Disclaimer: This is a simulated investment strategy for demonstration purposes only and not financial advice. Consult a professional financial advisor before making any investment decisions.*")

    return "\n".join(strategy_output)

