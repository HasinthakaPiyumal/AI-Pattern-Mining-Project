import numpy as np
import pandas as pd
from scipy.optimize import minimize
from scipy.stats import norm

def portfolio_optimization(expected_returns, cov_matrix, risk_free_rate=0.01):
    num_assets = len(expected_returns)
    args = (expected_returns, cov_matrix, risk_free_rate)

    # Function to calculate portfolio return
    def portfolio_return(weights, expected_returns):
        return np.sum(expected_returns * weights)

    # Function to calculate portfolio volatility
    def portfolio_volatility(weights, cov_matrix):
        return np.sqrt(np.dot(weights.T, np.dot(cov_matrix, weights)))

    # Objective function for minimizing volatility (for a given return target)
    def min_volatility(weights, expected_returns, cov_matrix):
        return portfolio_volatility(weights, cov_matrix)

    # Constraints: weights sum to 1, and each weight is between 0 and 1
    constraints = ({'type': 'eq', 'fun': lambda x: np.sum(x) - 1})
    bounds = tuple((0, 1) for asset in range(num_assets))
    initial_weights = num_assets * [1. / num_assets]

    # Optimize for minimum volatility portfolio
    optimal_weights_min_vol = minimize(min_volatility, initial_weights, args=(expected_returns, cov_matrix),
                                    method='SLSQP', bounds=bounds, constraints=constraints)

    min_vol_portfolio = {{
        'weights': optimal_weights_min_vol.x,
        'return': portfolio_return(optimal_weights_min_vol.x, expected_returns),
        'volatility': portfolio_volatility(optimal_weights_min_vol.x, cov_matrix)
    }}

    return min_vol_portfolio

def monte_carlo_simulation(initial_investment, expected_annual_return, annual_volatility, years=10, num_simulations=10000):
    dt = 1/252  # Assuming 252 trading days in a year
    num_days = years * 252
    daily_returns = np.random.normal(expected_annual_return/252, annual_volatility/np.sqrt(252), (num_days, num_simulations))
    
    price_paths = np.zeros_like(daily_returns)
    price_paths[0] = initial_investment
    for t in range(1, num_days):
        price_paths[t] = price_paths[t-1] * (1 + daily_returns[t])

    final_portfolios = price_paths[-1]
    
    results = {{
        'median_final_value': np.median(final_portfolios),
        'percentile_5th': np.percentile(final_portfolios, 5),
        'percentile_95th': np.percentile(final_portfolios, 95),
        'loss_probability': np.sum(final_portfolios < initial_investment) / num_simulations
    }}
    return results


