# --- 4. Rejection Sampling Function ---
def rejection_sampling(
    llm: MockLLM,
    reward_model: MockRewardModel,
    query: str,
    num_candidates: int = 5
) -> str:
    """
    Generates N candidate responses from the LLM and selects the best one using the reward model.
    (AI Design Pattern: Rejection Sampling (Best-of-N))
    """
    print(f"\n[Rejection Sampling] Generating {num_candidates} candidates for query: '{query}'")
    candidates = llm.generate(query, num_return_sequences=num_candidates)
    
    scored_candidates = []
    for i, candidate in enumerate(candidates):
        score = reward_model.get_reward(query, candidate)
        scored_candidates.append((candidate, score))
        print(f"[Rejection Sampling]   Candidate {i+1} (Score: {score:.2f}): '{candidate[:70]}...' ")
    
    # Select the candidate with the highest reward score
    best_candidate, best_score = max(scored_candidates, key=lambda x: x[1])
    
    print(f"[Rejection Sampling] Selected Best (Score: {best_score:.2f}): '{best_candidate[:70]}...' ")
    return best_candidate

# --- 5. Intelligent Customer Support Agent ---
class CustomerSupportAgent:
    def __init__(self, llm: MockLLM, reward_model: MockRewardModel):
        self.llm = llm
        self.reward_model = reward_model
        print("\n[CustomerSupportAgent] Initialized.")

    def handle_query(self, query: str) -> str:
        """
        Handles a customer query by generating multiple responses and selecting the best one
        using rejection sampling based on the reward model.
        """
        print(f"\n[CustomerSupportAgent] Handling query: '{query}'")
        best_response = rejection_sampling(self.llm, self.reward_model, query, num_candidates=3)
        return best_response

