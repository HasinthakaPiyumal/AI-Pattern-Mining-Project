"""main.py - E-commerce Product Description Generator and Personalizer API
This file contains the consolidated code for the E-commerce Product Description Generator and Personalizer application.
It includes data models, LLM service abstraction, core logic, and the FastAPI application layer.
"""

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field
from typing import List, Dict, Optional
import uuid
import time

# --- 1. Data Models & Mocks (data_models.py) ---

class ProductInfo(BaseModel):
    """Represents basic information about a product."""
    name: str = Field(..., example="Organic Cotton T-Shirt")
    category: str = Field(..., example="Apparel")
    features: List[str] = Field(..., example=["100% organic cotton", "Unisex fit", "Sustainable production"])

class UserProfile(BaseModel):
    """Represents a user's profile and preferences."""
    user_id: str = Field(..., example="user_123")
    preferences: List[str] = Field(..., example=["eco-friendly", "luxury", "budget-conscious"])

class GeneratedDescription(BaseModel):
    """Represents a product description generated by the LLM."""
    description_id: str = Field(..., example="desc_abc")
    text: str = Field(..., example="A comfortable and stylish organic cotton t-shirt...")

class PersonalizedDescription(BaseModel):
    """Represents a product description personalized for a specific user."""
    original_description_id: str = Field(..., example="desc_abc")
    user_id: str = Field(..., example="user_123")
    personalized_text: str = Field(..., example="For the eco-conscious shopper, this organic cotton t-shirt...")

