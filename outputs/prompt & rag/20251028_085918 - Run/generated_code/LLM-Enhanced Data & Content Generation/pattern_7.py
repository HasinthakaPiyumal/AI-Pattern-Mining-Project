# --- 3. Core Logic (product_description_service.py) ---

class ProductDescriptionService:
    """Orchestrates product description generation and personalization."""
    def __init__(self, llm_service: LLMService):
        self.llm_service = llm_service

    def generate_product_description(self, product_info: ProductInfo) -> GeneratedDescription:
        """Generates a new product description using the LLM service."""
        description_text = self.llm_service.generate_description(product_info)
        new_description_id = str(uuid.uuid4())
        generated_desc = GeneratedDescription(
            description_id=new_description_id,
            text=description_text
        )
        MOCK_GENERATED_DESCRIPTIONS[new_description_id] = generated_desc
        return generated_desc

    def personalize_product_description(self, description_id: str, user_id: str) -> PersonalizedDescription:
        """Personalizes an existing product description for a specific user."""
        # Retrieve base description
        base_description_obj = MOCK_GENERATED_DESCRIPTIONS.get(description_id)
        if not base_description_obj:
            raise HTTPException(status_code=404, detail=f"Description with ID '{description_id}' not found.")
        base_description_text = base_description_obj.text

        # Retrieve user preferences
        user_profile = MOCK_USERS.get(user_id)
        if not user_profile:
            raise HTTPException(status_code=404, detail=f"User with ID '{user_id}' not found.")
        user_preferences = user_profile.preferences

        # Personalize using LLM service
        personalized_text = self.llm_service.personalize_description(
            base_description_text, user_preferences
        )

        return PersonalizedDescription(
            original_description_id=description_id,
            user_id=user_id,
            personalized_text=personalized_text
        )

# --- End of Core Logic ---


# --- 4. API Layer (main.py) ---

app = FastAPI(
    title="E-commerce LLM Product Description API",
    description="API for generating and personalizing e-commerce product descriptions using LLMs."
)

# Initialize services
llm_service_instance = LLMService()
product_description_service_instance = ProductDescriptionService(llm_service=llm_service_instance)

@app.post("/generate_description", response_model=GeneratedDescription, status_code=201)
async def generate_description_endpoint(product_info: ProductInfo):
    """Generate a new product description based on product information."""
    try:
        generated_desc = product_description_service_instance.generate_product_description(product_info)
        return generated_desc
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to generate description: {e}")

@app.post("/personalize_description", response_model=PersonalizedDescription)
async def personalize_description_endpoint(description_id: str, user_id: str):
    """Personalize an existing product description for a specific user."""
    try:
        personalized_desc = product_description_service_instance.personalize_product_description(description_id, user_id)
        return personalized_desc
    except HTTPException as e:
        raise e # Re-raise HTTPException from service layer
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to personalize description: {e}")


@app.get("/products", response_model=List[ProductInfo])
async def get_mock_products():
    """Retrieve available mock product information."""
    return list(MOCK_PRODUCTS.values())

@app.get("/users", response_model=List[UserProfile])
async def get_mock_users():
    """Retrieve available mock user profiles."""
    return list(MOCK_USERS.values())

@app.get("/descriptions", response_model=List[GeneratedDescription])
async def get_generated_descriptions():
    """Retrieve all currently generated mock descriptions."""
    return list(MOCK_GENERATED_DESCRIPTIONS.values())

