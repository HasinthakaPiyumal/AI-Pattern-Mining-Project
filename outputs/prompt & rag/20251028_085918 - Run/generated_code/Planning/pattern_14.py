# --- 1. Data Models (Pydantic) ---
class PatientData(BaseModel):
    patient_id: str
    age: int
    gender: str
    diagnoses: List[str]
    medications: List[str]
    allergies: List[str] = []
    lab_results: Dict[str, Any] = {}
    notes: Optional[str] = None

class MedicalGuideline(BaseModel):
    guideline_id: str
    disease: str
    recommendations: List[str]
    contraindications: List[str] = []
    dosage_info: Dict[str, str] = {}

class TreatmentPlanStep(BaseModel):
    step_id: str
    description: str
    action_type: str  # e.g., 'medication_adjustment', 'lifestyle_change', 'monitoring'
    details: Dict[str, Any] = {}
    dependencies: List[str] = [] # Other step_ids this step depends on

class TreatmentPlan(BaseModel):
    plan_id: str
    patient_id: str
    goal: str
    steps: List[TreatmentPlanStep]
    status: str = "draft"
    version: int = 1

